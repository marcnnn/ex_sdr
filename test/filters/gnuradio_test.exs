Code.require_file("test_kit.exs", __DIR__)

defmodule ExSdr.Filters.GnuRadioTest do
  @moduledoc """
  Per case in test/dsp_cases/filters:

    1. the float instance against GNU Radio on the same input (the
       fixtures are committed, GNU Radio is not needed to run this),
    2. each fixed-point variant against the float instance,
    3. the width check (`NxFixed.analyze/3`) of each fixed-point variant.

  Bounds and their reasoning are in the case files; they are generated by
  test/filters/gen_cases.exs from the tap rounding errors.
  """
  use ExUnit.Case, async: true

  alias ExSdr.Filters.TestKit
  alias ExSdr.Test.GnuRadioFixture, as: F
  alias NxFixed.Num

  @moduletag timeout: 600_000

  setup_all do
    runs =
      Map.new(TestKit.family(), fn {case, data} ->
        float = TestKit.run(TestKit.block(case, Num.float()), data.input)
        {case["name"], %{case: case, data: data, float: float}}
      end)

    %{runs: runs}
  end

  for {case, _data} <- TestKit.family() do
    @name case["name"]
    @case case

    test "#{case["name"]}: float instance vs GNU Radio (#{case["description"]})", %{runs: runs} do
      %{case: case, data: data, float: float} = runs[@name]
      shift = case["reference_shift"] || 0
      {reference, got} = TestKit.align(data.reference, float, shift)

      # The same number of items, up to the end effects of GNU Radio's blocks
      # (fft_filter works in whole FFT blocks and drops the tail).
      assert length(reference) >= length(data.reference) - 16
      assert length(got) == length(reference)

      assert_close(
        reference,
        got,
        case["float_vs_gnuradio"],
        "#{@name} float vs GNU Radio",
        data.input
      )
    end

    for variant <- case["fixed_vs_float"] do
      @variant variant

      test "#{case["name"]}: #{variant["variant"]} vs float instance", %{runs: runs} do
        %{case: case, data: data, float: float} = runs[@name]
        fixed = TestKit.run(TestKit.block(case, F.format(@variant["format"])), data.input)
        assert length(fixed) == length(float)

        assert_close(
          float,
          fixed,
          @variant,
          "#{@name} #{@variant["variant"]} vs float",
          data.input
        )
      end

      test "#{case["name"]}: #{variant["variant"]} passes the width check" do
        block = TestKit.block(@case, F.format(@variant["format"]))
        assert {:ok, _graph} = TestKit.width_check(block)
      end
    end
  end

  defp assert_close(reference, signal, expect, label, input) do
    {worst, i} = F.worst_sample(reference, signal)

    assert worst <= expect["max_error_lsb"], """
    #{label}: sample #{i} is off by #{Float.round(worst, 3)} LSB (bound #{expect["max_error_lsb"]})
      input:     #{inspect(Enum.at(input, i))}
      reference: #{inspect(Enum.at(reference, i))}
      got:       #{inspect(Enum.at(signal, i))}
      bound:     #{expect["rationale"]}
    """

    snr = F.snr_db(reference, signal)

    assert snr >= expect["snr_db_min"],
           "#{label}: SNR #{Float.round(snr, 1)} dB < #{expect["snr_db_min"]} dB (#{expect["rationale"]})"
  end
end
