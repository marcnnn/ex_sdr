Code.require_file("support/helper.exs", __DIR__)

defmodule ExSdr.Carrier.GnuRadioCasesTest do
  @moduledoc """
  The carrier cases (test/dsp_cases/carrier, GNU Radio output in
  test/fixtures/gnuradio/carrier, regenerated by
  `podman run ... python3 test/gnuradio/carrier_golden.py`, see that file)
  against the blocks, per case:

    1. the float instance against GNU Radio on the same input, every output
       port, from sample 0 (the loops run the same recurrence as GNU Radio, so
       their transient is reproduced, not skipped);
    2. each fixed-point variant against the float instance (running one also
       runs `NxFixed`'s width check, so passing means the format has no
       undeclared overflow); the bounds say where the loop is compared from
       (`"skip"`);
    3. a stream cut in pieces gives the output of the whole: bit-exact for
       fixed point, float within rounding;
    4. for loops, the GNU Radio output itself shows lock (`"lock"`): the
       frequency port settles on the true offset (mean over the tail).

  Bounds and the reasoning behind them are in the case files (`"rationale"`).
  A bound is a number per output port: the largest absolute difference (complex:
  distance), or for a byte port the number of different items.
  """
  use ExUnit.Case, async: true

  alias ExSdr.Carrier.TestHelper, as: H

  @moduletag timeout: 900_000

  @paths H.case_paths()
         |> Enum.filter(fn p ->
           (p |> File.read!() |> JSON.decode!() |> Map.get("compare") || "ports") == "ports"
         end)

  setup_all do
    runs =
      @paths
      |> Task.async_stream(
        fn path ->
          {case, data} = H.load(path)
          {float, _} = H.run(case, data, NxFixed.Num.float())

          fixed =
            for v <- case["fixed_vs_float"] || [], into: %{} do
              {out, _} = H.run(case, data, H.format(v["format"]))
              {v["variant"], out}
            end

          {case["name"], %{case: case, data: data, float: float, fixed: fixed}}
        end,
        max_concurrency: 4,
        timeout: 900_000,
        ordered: false
      )
      |> Map.new(fn {:ok, r} -> r end)

    %{runs: runs}
  end

  for path <- @paths do
    @external_resource path
    case = path |> File.read!() |> JSON.decode!()
    @name case["name"]

    test "#{case["name"]}: float instance vs GNU Radio (#{case["description"]})", %{runs: runs} do
      %{case: case, data: data, float: float} = runs[@name]
      expect = case["float_vs_gnuradio"]
      assert_ports(data.ports, float, case, expect, "#{@name} float vs GNU Radio")
    end

    for variant <- case["fixed_vs_float"] || [] do
      @variant variant
      test "#{case["name"]}: #{variant["variant"]} vs float instance", %{runs: runs} do
        %{case: case, float: float, fixed: fixed} = runs[@name]

        assert_ports(
          float,
          fixed[@variant["variant"]],
          case,
          @variant,
          "#{@name} #{@variant["variant"]} vs float"
        )
      end
    end

    if case["fixed_vs_float"] do
      test "#{case["name"]}: split into pieces gives the same output", %{runs: runs} do
        %{case: case, data: data, fixed: fixed, float: float} = runs[@name]
        v = hd(case["fixed_vs_float"])
        n = length(data.input)

        split = H.run_split(case, data, H.format(v["format"]), [div(n, 3)])
        assert split == fixed[v["variant"]], "#{@name}: fixed point differs when split"

        split_float = H.run_split(case, data, NxFixed.Num.float(), [div(n, 3)])
        assert_ports(float, split_float, case, %{"bounds" => 1.0e-4}, "#{@name} float split")
      end
    end

    if case["lock"] do
      test "#{case["name"]}: GNU Radio's loop locks on the offset", %{runs: runs} do
        %{data: data, case: case} = runs[@name]
        %{"port" => port, "expect" => expect, "tol" => tol, "after" => from} = case["lock"]
        tail = data.ports |> Enum.at(port) |> Enum.drop(from)
        mean = Enum.sum(tail) / length(tail)
        assert abs(mean - expect) < tol, "mean #{mean} after #{from} samples, offset #{expect}"
      end
    end
  end

  # `expect["bounds"]`: a list, one per port (or a number for all), `expect["skip"]`.
  defp assert_ports(reference, got, case, expect, label) do
    specs = case["outputs"] || [%{}]
    bounds = bounds(expect["bounds"], length(specs))
    skip = expect["skip"] || 0

    for {{spec, ref}, mine, bound, k} <-
          Enum.zip([Enum.zip(specs, reference), got, bounds, 0..99]) do
      assert length(mine) == length(ref),
             "#{label} port #{k}: #{length(mine)} items, expected #{length(ref)}"

      if spec["type"] == "bytes" do
        miss = ref |> Enum.zip(mine) |> Enum.drop(skip) |> Enum.count(fn {a, b} -> a != b end)

        assert miss <= bound,
               "#{label} port #{k}: #{miss} different items > #{bound} (#{expect["rationale"]})"
      else
        worst = H.max_diff(ref, mine, skip, spec["circular"] || false)

        assert worst <= bound,
               "#{label} port #{k}: #{worst} > #{bound}, skipping #{skip} (#{expect["rationale"]})"
      end
    end
  end

  defp bounds(b, n) when is_list(b) and length(b) == n, do: b
  defp bounds(b, n) when is_number(b), do: List.duplicate(b, n)
end
