#!/usr/bin/env python3
"""GNU Radio runner for the carrier family's cases (test/dsp_cases/carrier/*.json).

Usage: carrier_golden.py <cases dir> <output dir>

Like digital_golden.py (same case format, output files and
"args" expressions that may build objects such as constellations or
adaptive algorithms), plus what the carrier blocks need and golden.py's chain
cannot express:

* "input": {"type": "complex", "source": {...}}: a PSK/QAM signal made with
  GNU Radio blocks, then quantised to Q15 like every input. Source keys:
  "constellation" (python expression for the constellation object, e.g.
  "digital.constellation_qpsk().base()"), "sps" (default 1), "rolloff"
  (RRC pulse shaping when sps > 1), "freq_offset" (cycles per sample),
  "phase" (radians), "multipath" (list of [re, im] taps at the sample rate),
  "rms" (target RMS of the signal before noise), "noise_rms" (per component),
  "head" (list of symbol indices forced at the start, e.g. a sync word).
  Without "source" the input comes from golden.make_input (tones, noise).
* "input.tags": [{"offset": n, "key": "train_start", "value": 0}]: stream tags
  on the source.
* "outputs": [{"type": ..., "vlen": n}, ...]: the output ports of the last block
  (types complex, real, bytes, ushort; ushort is stored as float32). Port 0
  goes to gnuradio.f32le (or .u8 for bytes) like golden.py, port k to
  out<k>.f32le / out<k>.u8. Without it the case's "output" type is port 0.
* "tags": [key, ...]: the stream tags of output port 0 with those keys, in
  tags.json as [{"offset", "key", "value"}].
* "probe": [method, ...]: methods called on the last block after the run
  (e.g. probe_mpsk_snr_est_c.snr), written to tags.json under "probe".

The python expression environment has pi, math, numpy as np, the modules
blocks, filter, analog, digital, gr, the case's params, and `points` (the
source constellation's points as complex numbers) and `head_points`.

Run it with (rootless podman, image exhdl-gnuradio):

  podman run --rm -v "$PWD/test:/work/test:ro,Z" \\
    -v "$PWD/test/dsp_cases/carrier:/cases:ro,Z" \\
    -v "$PWD/test/fixtures/gnuradio/carrier:/out:Z" -w /work exhdl-gnuradio \\
    python3 test/gnuradio/carrier_golden.py /cases /out

or simply: scripts/gnuradio_golden.sh test/fixtures/gnuradio/carrier test/dsp_cases/carrier
"""
import glob
import hashlib
import importlib
import json
import math
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

import golden  # noqa: E402
import numpy as np  # noqa: E402
import pmt  # noqa: E402
from gnuradio import analog, blocks, digital, filter, gr  # noqa: E402

FULL_SCALE = 32768.0


def environment(params, extra=None):
    env = {
        "__builtins__": {
            "list": list,
            "range": range,
            "len": len,
            "int": int,
            "float": float,
            "tuple": tuple,
            "complex": complex,
            "abs": abs,
        },
        "pi": math.pi,
        "math": math,
        "np": np,
        "blocks": blocks,
        "filter": filter,
        "analog": analog,
        "digital": digital,
        "gr": gr,
    }
    env.update(params)
    env.update(extra or {})
    env["scaled"] = scaled
    return env


def scaled(cons, k):
    """A constellation with the points of `cons` times `k` (no normalisation)."""
    points = [k * p for p in cons.points()]
    return digital.constellation_calcdist(
        points,
        list(cons.pre_diff_code()),
        cons.rotational_symmetry(),
        1,
        digital.constellation.NO_NORMALIZATION,
    ).base()


def make_block(spec, env):
    module, name = spec["block"].rsplit(".", 1)
    cls = getattr(importlib.import_module("gnuradio." + module), name)
    args = [eval(a, env) if isinstance(a, str) else a for a in spec.get("args", [])]
    return cls(*args)


def make_source_signal(src, samples, rng, env):
    """The transmitted signal of a case's "source", generated by GNU Radio blocks."""
    cons = eval(src["constellation"], env)
    points = list(cons.points())
    env["points"] = points
    sps = src.get("sps", 1)
    nsym = samples // sps + 8
    idx = rng.integers(0, len(points), nsym)
    head = src.get("head", [])
    idx[: len(head)] = head
    for ins in src.get("inserts", []):
        idx[ins["at"] : ins["at"] + len(ins["indices"])] = ins["indices"]
    env["head_points"] = [points[i] for i in head]

    chain = [
        blocks.vector_source_b([int(i) for i in idx]),
        digital.chunks_to_symbols_bc(points),
    ]
    if sps > 1:
        taps = filter.firdes.root_raised_cosine(
            1.0, float(sps), 1.0, src.get("rolloff", 0.35), 11 * sps + 1
        )
        chain.append(filter.interp_fir_filter_ccf(sps, taps))
    if src.get("multipath"):
        chain.append(filter.fir_filter_ccc(1, [complex(a, b) for a, b in src["multipath"]]))
    if src.get("freq_offset"):
        chain.append(blocks.rotator_cc(2 * math.pi * src["freq_offset"]))
    sink = blocks.vector_sink_c()
    tb = gr.top_block()
    tb.connect(*chain, sink)
    tb.run()
    x = np.asarray(sink.data(), dtype=np.complex128)[:samples]
    x = x * np.exp(1j * src.get("phase", 0.0))
    # Scale on the signal before the channel noise: RMS target.
    x = x * (src.get("rms", 0.3) / np.sqrt(np.mean(np.abs(x) ** 2)))
    noise = src.get("noise_rms", 0.0)
    x = x + noise * (rng.standard_normal(samples) + 1j * rng.standard_normal(samples))
    return np.stack([golden.q15(x.real), golden.q15(x.imag)], axis=1).reshape(-1)


def run_case(case):
    rng = np.random.default_rng(case["seed"])
    env = environment(case["params"])
    in_spec = case["input"]
    if "source" in in_spec:
        x16 = make_source_signal(in_spec["source"], case["samples"], rng, env)
    else:
        x16 = golden.make_input(in_spec, case["samples"], rng)

    if in_spec["type"] == "bytes":
        source = blocks.vector_source_b(x16.tolist())
    elif in_spec["type"] == "complex":
        data = (x16[0::2] + 1j * x16[1::2]).astype(np.complex64) / FULL_SCALE
        tags = []
        for t in in_spec.get("tags", []):
            tag = gr.tag_t()
            tag.offset = t["offset"]
            tag.key = pmt.intern(t["key"])
            tag.value = pmt.from_long(t.get("value", 0))
            tags.append(tag)
        source = blocks.vector_source_c(data, False, 1, tags)
    else:
        source = blocks.vector_source_f(x16.astype(np.float32) / FULL_SCALE)

    out_specs = (
        case["outputs"]
        if "outputs" in case
        else [{"type": case.get("output", {}).get("type", in_spec["type"])}]
    )
    kinds = {
        "bytes": blocks.vector_sink_b,
        "complex": blocks.vector_sink_c,
        "real": blocks.vector_sink_f,
        "ushort": blocks.vector_sink_s,
    }
    sinks = [kinds[o["type"]](o.get("vlen", 1)) for o in out_specs]

    chain = [make_block(b, env) for b in case["gnuradio"]]
    tb = gr.top_block()
    tb.connect(source, *chain)
    for k, sink in enumerate(sinks):
        tb.connect((chain[-1], k), sink)
    tb.run()

    outs = []
    for spec, sink in zip(out_specs, sinks):
        out = np.asarray(sink.data())
        if spec["type"] == "ushort":
            out = out.astype(np.float32)
        if spec["type"] == "bytes":
            outs.append(out.astype(np.uint8))
        else:
            if spec["type"] == "complex":
                out = np.stack([out.real, out.imag], axis=1).reshape(-1)
            outs.append(out.astype(np.float32))

    extra = {}
    if case.get("tags") and sinks:
        wanted = set(case["tags"])
        found = []
        for t in sinks[0].tags():
            key = pmt.symbol_to_string(t.key)
            if key in wanted:
                found.append({"offset": int(t.offset), "key": key, "value": pmt.to_python(t.value)})
        extra["tags"] = found
    if case.get("probe"):
        values = {m: getattr(chain[-1], m)() for m in case["probe"]}
        extra["probe"] = {
            m: [v.real, v.imag] if isinstance(v, complex) else float(v) for m, v in values.items()
        }
    return x16, outs, extra


def write_case(case, raw, out_dir):
    x16, outs, extra = run_case(case)
    case_dir = os.path.join(out_dir, case["name"])
    os.makedirs(case_dir, exist_ok=True)
    if x16.dtype == np.uint8:
        x16.tofile(os.path.join(case_dir, "input.u8"))
    else:
        x16.astype("<i2").tofile(os.path.join(case_dir, "input.s16le"))
    for k, ref in enumerate(outs):
        stem = "gnuradio" if k == 0 else f"out{k}"
        if ref.dtype == np.uint8:
            ref.tofile(os.path.join(case_dir, stem + ".u8"))
        else:
            ref.astype("<f4").tofile(os.path.join(case_dir, stem + ".f32le"))
    if not outs:
        # a probe without output ports: an empty reference keeps the loader happy
        open(os.path.join(case_dir, "gnuradio.f32le"), "wb").close()
    if extra:
        with open(os.path.join(case_dir, "tags.json"), "w") as f:
            json.dump(extra, f, indent=1, sort_keys=True)
            f.write("\n")
    manifest = {
        "case": case["name"],
        "case_sha256": hashlib.sha256(raw).hexdigest(),
        "gnuradio": gr.version(),
        "numpy": np.__version__,
    }
    with open(os.path.join(case_dir, "manifest.json"), "w") as f:
        json.dump(manifest, f, indent=2, sort_keys=True)
        f.write("\n")
    print(f"{case['name']}: {case['samples']} samples")


def main(cases_dir, out_dir):
    for path in sorted(glob.glob(os.path.join(cases_dir, "*.json"))):
        with open(path, "rb") as f:
            raw = f.read()
        write_case(json.loads(raw), raw, out_dir)


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
