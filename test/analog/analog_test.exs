defmodule ExSdr.AnalogTest do
  @moduledoc """
  The analog blocks against GNU Radio (output committed in
  test/fixtures/gnuradio/analog, regenerated by
  `scripts/gnuradio_golden.sh test/fixtures/gnuradio/analog test/dsp_cases/analog`)
  and against each other, per case (test/dsp_cases/analog/*.json):

    1. the float instance against GNU Radio on the same input;
    2. each fixed-point variant against the float instance (running a variant
       also runs `NxFixed`'s width check, so passing means the format has no
       undeclared overflow);
    3. a stream cut in pieces gives the output of the whole (bit-exact for
       fixed point).

  Bounds and the reasoning behind them are in the case files. Loops (PLL) are
  compared from `"skip"` samples on where the case says so; the lock time is
  in docs/blocks/analog.md.
  """
  use ExUnit.Case, async: true

  Code.require_file("helper.exs", __DIR__)
  alias ExSdr.Analog.TestHelper, as: H
  alias ExSdr.Test.GnuRadioFixture, as: F

  @moduletag timeout: 900_000

  @paths Path.wildcard(Path.join([F.cases_dir(), "analog", "*.json"])) |> Enum.sort()

  setup_all do
    # Float and fixed runs of every case, compiled in parallel.
    runs =
      @paths
      |> Task.async_stream(
        fn path ->
          case = F.read_case(path)
          dir = Path.join([F.fixtures_dir(), "analog"])
          data = F.load(case, path, dir)
          {float, _} = H.run(case, data.input, NxFixed.Num.float())

          fixed =
            for v <- case["fixed_vs_float"], into: %{} do
              {out, _} = H.run(case, data.input, H.format(v["format"]))
              {v["variant"], out}
            end

          {case["name"], %{case: case, data: data, float: float, fixed: fixed}}
        end,
        max_concurrency: 4,
        timeout: 900_000,
        ordered: false
      )
      |> Map.new(fn {:ok, r} -> r end)

    %{runs: runs}
  end

  for path <- @paths do
    @external_resource path
    case = F.read_case(path)
    @name case["name"]

    test "#{case["name"]}: float instance vs GNU Radio (#{case["description"]})", %{runs: runs} do
      %{case: case, data: data, float: float} = runs[@name]
      expect = case["float_vs_gnuradio"]

      assert_close(
        data.reference,
        float,
        expect,
        "#{@name} float vs GNU Radio",
        expect["skip"] || 0
      )
    end

    for variant <- case["fixed_vs_float"] do
      @variant variant
      test "#{case["name"]}: #{variant["variant"]} vs float instance", %{runs: runs} do
        %{float: float, fixed: fixed} = runs[@name]

        assert_close(
          float,
          fixed[@variant["variant"]],
          @variant,
          "#{@name} #{@variant["variant"]} vs float",
          @variant["skip"] || 0
        )
      end
    end

    test "#{case["name"]}: split into pieces gives the same output", %{runs: runs} do
      %{case: case, data: data, fixed: fixed, float: float} = runs[@name]
      v = hd(case["fixed_vs_float"])
      cuts = [120, 1200]

      split = H.run_split(case, data.input, H.format(v["format"]), cuts)
      assert split == fixed[v["variant"]], "#{@name}: fixed point differs when split"

      # The float instance may fuse differently in a loop of another length.
      split_float = H.run_split(case, data.input, NxFixed.Num.float(), cuts)

      assert_close(
        float,
        split_float,
        %{"max_error_lsb" => 0.05, "snr_db_min" => 120},
        "#{@name} float split",
        0
      )
    end
  end

  # `expect` has max_error_lsb, snr_db_min and rationale.
  defp assert_close(reference, signal, expect, label, skip) do
    assert length(signal) == length(reference),
           "#{label}: #{length(signal)} samples, expected #{length(reference)}"

    {worst, snr} = H.compare(reference, signal, skip)

    assert worst <= expect["max_error_lsb"], """
    #{label}: worst sample is off by #{Float.round(worst, 3)} LSB (bound #{expect["max_error_lsb"]}), skipping #{skip}
      bound: #{expect["rationale"]}
    """

    assert snr >= expect["snr_db_min"],
           "#{label}: SNR #{Float.round(snr, 1)} dB < #{expect["snr_db_min"]} dB (#{expect["rationale"]})"
  end
end
